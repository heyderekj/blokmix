/**
 * Bundles the shader player (resources/js/frame/shader-runtime-entry.ts, with the
 * six Paper Shaders it runs) into resources/js/core/export/shaders-runtime.generated.ts,
 * as a string: canvas frames load it on demand and exports write it as /mx-shaders.js.
 *   npx vite-node scripts/build-shaders.ts
 *
 * Paper Shaders (@paper-design/shaders) is Apache-2.0; the bundle keeps its notice.
 * Run this again after updating the package (a test checks the versions match).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'node_modules/@paper-design/shaders/package.json'), 'utf8')) as { version: string; license: string }

const out = await build({
  configFile: false,
  logLevel: 'warn',
  resolve: { alias: { '@': join(root, 'resources/js') } },
  build: {
    write: false,
    minify: true,
    lib: { entry: join(root, 'resources/js/frame/shader-runtime-entry.ts'), formats: ['iife'], name: 'mxShadersRuntime', fileName: () => 'mx-shaders.js' },
  },
})
const outputs = (Array.isArray(out) ? out : [out]) as { output: { type: string; code?: string }[] }[]
const code = outputs.flatMap((o) => o.output).find((c) => c.type === 'chunk')?.code
if (!code) throw new Error('No bundle came out')

const notice = `/*! Blokmix shader player. Includes Paper Shaders ${pkg.version} (https://shaders.paper.design), Copyright 2026 Paper, ${pkg.license} (http://www.apache.org/licenses/LICENSE-2.0). */`
const js = `${notice}\n${code.trim()}\n`
writeFileSync(
  join(root, 'resources/js/core/export/shaders-runtime.generated.ts'),
  `// Generated by scripts/build-shaders.ts from resources/js/frame/shader-runtime.ts. Don't edit.\n` +
    `export const PAPER_SHADERS_VERSION = ${JSON.stringify(pkg.version)}\n` +
    `export const SHADERS_JS = ${JSON.stringify(js)}\n`,
)
console.log(`mx-shaders.js: ${(js.length / 1024).toFixed(1)} KB (Paper Shaders ${pkg.version})`)
